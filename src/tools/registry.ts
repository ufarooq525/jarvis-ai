export class ToolRegistry {
  private readonly byId = new Map<string, ToolManifest>();

  constructor(manifests: ToolManifest[] = PHASE1_MANIFESTS) {
    for (const m of manifests) this.byId.set(m.tool_id, m);
  }

  get(tool_id: string): ToolManifest | undefined {
    return this.byId.get(tool_id);
  }

  require(tool_id: string): ToolManifest {
    const m = this.byId.get(tool_id);
    if (!m) throw new Error(`Tool not registered: ${tool_id}`);
    return m;
  }

  /**
   * Register a capability. New tools default to SHADOW min trust unless the
   * caller explicitly sets a higher tier (still subject to policy).
   */
  register(manifest: ToolManifest): void {
    const enforced: ToolManifest = {
      ...manifest,
      required_trust_tier: manifest.required_trust_tier ?? defaultManifestTrust(),
    };
    if (!enforced.required_trust_tier) {
      enforced.required_trust_tier = defaultManifestTrust();
    }
    this.byId.set(enforced.tool_id, enforced);
  }

  list(): ToolManifest[] {
    return [...this.byId.values()];
  }
}
